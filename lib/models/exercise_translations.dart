class ExerciseTranslations {
static String name(Exercise exercise, Locale locale) {
final lang = locale.languageCode;
return _get(exercise.name, lang, _names);
}

static String muscles(Exercise exercise, Locale locale) {
return _get(
exercise.muscles,
locale.languageCode,
_muscles,
);
}

static String step(String value, Locale locale) {
return _get(value, locale.languageCode, _steps);
}

static String instruction(String value, Locale locale) {
return _get(value, locale.languageCode, _instructions);
}

static String _get(
String value,
String lang,
Map<String, Map<String, String>> translations,
) {
if (lang == 'en') return value;

return translations[lang]?[value] ?? value;
}

